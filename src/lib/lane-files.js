export const EXCLUDE_BEGIN = '# BEGIN laines lane (lane-local files, never committed)';
export const EXCLUDE_END = '# END laines lane';
export const LANE_EXCLUDES = [
  '/.ai/.lane.json',
  '/.ai/README.md',
  '/.ai/context/',
  '/.ai/plans/',
  '/.laines.env',
  '/CLAUDE.local.md',
  '/AGENTS.md',
  '/GEMINI.md',
  '/.claude/settings.local.json',
  '/.mcp.json',
  '/*.pre-laines*',
];

// Double-quoted and escaped, so `source .laines.env` survives spaces and shell characters.
const q = (value) => `"${String(value).replace(/[\\"$`]/g, (c) => `\\${c}`)}"`;

// Spec §8.3: the lane's variables, shared by .laines.env and the hook environment.
export function laneVars({ lane, number, containerId, laneDir, containerDir, ports, branch, compose, adopted }) {
  const vars = {
    LANE_NAME: lane,
    LANE_NUMBER: number,
    LANE_ID: laneId(containerId, lane),
    LANE_DIR: laneDir,
    CONTAINER_DIR: containerDir,
    CONTAINER_ID: containerId,
    LANE_PORT_BASE: ports[0],
    LANE_PORT_COUNT: ports[1] - ports[0] + 1,
    LANE_SUFFIX: laneSuffix(containerId, number),
    LANE_BRANCH: branch,
    LANE_ENV_FILE: join(laneDir, '.laines.env'),
    // An adopted checkout keeps the project's own PORT; laines' block stays in LANE_PORT_BASE/COUNT.
    ...(adopted ? {} : { PORT: ports[0] }),
    COMPOSE_PROJECT_NAME: compose ?? composeProject(containerId, number),
  };
  return Object.fromEntries(Object.entries(vars).map(([k, v]) => [k, String(v)]));
}

export function laneEnv(args) {
  const lines = Object.entries(laneVars(args)).map(([k, v]) => `${k}=${q(v)}`);
  return (
    `# Generated by laines for lane ${args.lane}. Source it before starting services.\n` +
    '# `laines refresh` rewrites this file and re-runs post-create: hand edits are lost.\n' +
    (args.adopted ? "# Adopted checkout: PORT is not set, so the project's own port settings stay in effect.\n" : '') +
    `${lines.join('\n')}\n`
  );
}

// The arguments laneEnv/laneVars take for a lane, so the real write and the dry run agree.
export const envArgs = (ctx, { name, number, laneDir, branch, ports, compose, adopted }) => (
  { lane: name, number, containerId: ctx.id, laneDir, containerDir: ctx.root, ports, branch, compose, adopted }
);

// Keys laines owns in .laines.env; anything else was appended by a hook and is re-added by post-create.
const OWNED_ENV = /^(LANE_|CONTAINER_|PORT$|COMPOSE_PROJECT_NAME$)/;
const unq = (v) => (v.startsWith('"') && v.endsWith('"') ? v.slice(1, -1).replace(/\\([\\"$`])/g, '$1') : v);

// What rewriting .laines.env would change, key by key: [{ key, from, to }] (null = absent).
export function envChanges(file, args) {
  const have = {};
  if (existsSync(file)) {
    for (const line of readFileSync(file, 'utf8').split('\n')) {
      const m = /^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/.exec(line);
      if (m) have[m[1]] = unq(m[2]);
    }
  }
  const want = laneVars(args);
  return [
    ...Object.keys(want).filter((k) => have[k] !== want[k]).map((key) => ({ key, from: have[key] ?? null, to: want[key] })),
    ...Object.keys(have).filter((k) => !(k in want) && OWNED_ENV.test(k)).map((key) => ({ key, from: have[key], to: null })),
  ];
}

// Exit 0 = tracked, 1 = not tracked; anything else (fatal, spawn error) must not read as "not tracked".
export function isTracked(deps, repoDir, rel) {
  const args = ['ls-files', '--error-unmatch', '--', rel];
  const r = deps.git(args, { cwd: repoDir });
  if (r.error || (r.status !== 0 && r.status !== 1)) throw new GitError(args, r);
  return r.status === 0;
}

// What laines itself writes inside each directory entry, used when the repository commits that directory.
const OWN_FILES = {
  '/.ai/context/': ['/.ai/context/README.md'],
  '/.ai/plans/': ['/.ai/plans/README.md'],
};

// Tracked paths among `rels`, in one git call (the pathspec of a directory lists what is under it).
function trackedAmong(deps, repoDir, rels) {
  if (!rels.length) return [];
  return gitOut(deps, ['ls-files', '-z', '--', ...rels], repoDir).split('\0').filter(Boolean);
}

const isUnder = (tracked, rel) => tracked.some((t) => t === rel || t.startsWith(`${rel}/`));

// True when the repository tracks anything under relDir: that directory is project content here.
export function commitsUnder(deps, repoDir, relDir) {
  return trackedAmong(deps, repoDir, [relDir]).length > 0;
}

// The block lists only what laines really hides. An exact file the repository tracks is left out
// (excluding it does nothing). A directory the repository tracks something under is replaced by the
// files laines writes there, so the project's own files, new ones included, stay visible to git.
export function laneExcludes(deps, laneDir) {
  const rels = LANE_EXCLUDES.filter((e) => !e.includes('*'))
    .flatMap((e) => [e, ...(OWN_FILES[e] ?? [])]).map((e) => e.slice(1).replace(/\/$/, ''));
  const tracked = trackedAmong(deps, laneDir, rels);
  const keep = (rel) => !isUnder(tracked, rel);
  return LANE_EXCLUDES.flatMap((entry) => {
    if (entry.includes('*')) return [entry];
    const rel = entry.slice(1);
    if (!entry.endsWith('/')) return keep(rel) ? [entry] : [];
    if (keep(rel.slice(0, -1))) return [entry];
    return (OWN_FILES[entry] ?? []).filter((f) => keep(f.slice(1)));
  });
}

const excludeFile = (deps, laneDir) => {
  const rel = gitOut(deps, ['rev-parse', '--git-path', 'info/exclude'], laneDir).trim();
  return isAbsolute(rel) ? rel : join(laneDir, rel);
};

// Entries the lane's exclude block would gain or lose: { added, removed }.
export function excludeChanges(deps, laneDir) {
  const file = excludeFile(deps, laneDir);
  const cur = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const b = cur.indexOf(EXCLUDE_BEGIN);
  const e = cur.indexOf(EXCLUDE_END);
  const have = b === -1 ? [] : cur.slice(b, e > b ? e : undefined).split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
  const want = laneExcludes(deps, laneDir);
  return { added: want.filter((l) => !have.includes(l)), removed: have.filter((l) => !want.includes(l)) };
}

export function upsertExclude(deps, laneDir) {
  const file = excludeFile(deps, laneDir);
  const cur = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const block = [EXCLUDE_BEGIN, ...laneExcludes(deps, laneDir), EXCLUDE_END].join('\n');
  const b = cur.indexOf(EXCLUDE_BEGIN);
  const e = cur.indexOf(EXCLUDE_END);
  const next = b !== -1 && e > b
    ? cur.slice(0, b) + block + cur.slice(e + EXCLUDE_END.length)
    : `${cur ? cur.replace(/\n*$/, '\n\n') : ''}${block}\n`;
  if (next === cur) return;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, next);
}

// Top-level entries of relDir that hold no tracked file: the lane's own, safe to move or delete.
export function untrackedEntries(deps, repoDir, relDir) {
  const dir = join(repoDir, relDir);
  if (!existsSync(dir)) return [];
  const isRepo = existsSync(join(repoDir, '.git'));
  const tracked = isRepo ? gitOut(deps, ['ls-files', '-z', '--', relDir], repoDir).split('\0').filter(Boolean) : [];
  return readdirSync(dir)
    .filter((entry) => {
      const rel = `${relDir}/${entry}`;
      return !tracked.some((t) => t === rel || t.startsWith(`${rel}/`));
    })
    .sort();
}

// Spec §4. Never overwrites a file the repository tracks: a lane must not change project files
// behind the developer's back. Those are skipped and reported.
// `dryRun` runs the same decisions without writing anything and returns what it would write or skip.
export function writeLaneFiles(ctx, deps, lane, { dryRun = false } = {}) {
  const { name, number, laneDir, branch, ports } = lane;
  const vars = {
    lane: name,
    laneId: laneId(ctx.id, name),
    containerId: ctx.id,
    containerDir: ctx.root,
    branch,
    portStart: ports[0],
    portEnd: ports[1],
  };
  const written = [];
  const skipped = [];
  if (!dryRun) {
    upsertExclude(deps, laneDir); // first, so nothing written below ever shows in git status
    mkdirSync(join(laneDir, '.ai', 'context'), { recursive: true });
    mkdirSync(join(laneDir, '.ai', 'plans'), { recursive: true });
  }

  const tracked = (rel) => {
    if (!isTracked(deps, laneDir, rel)) return false;
    skipped.push({ file: rel, reason: 'tracked by the repository' });
    return true;
  };
  const put = (rel, content) => {
    if (tracked(rel)) return;
    if (!dryRun) {
      const file = join(laneDir, rel);
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, content);
    }
    written.push(rel);
  };
  // The container's copies of the lane templates win, so a team can customise them.
  const template = (file) => {
    // `_<name>` first, then the old `<name>` of a container not yet migrated, then the package copy.
    // From layout 2 on, a plain-named file is the project's own, never a laines template.
    const names = (ctx.layout ?? 1) < CURRENT_LAYOUT ? [`_${file}`, file] : [`_${file}`];
    const own = names.map((n) => join(ctx.paths.templatesDir, n)).find((f) => existsSync(f));
    return renderTemplate(own ? readFileSync(own, 'utf8') : readTemplate(file), vars);
  };

  if (!tracked('.ai/.lane.json')) {
    if (!dryRun) {
      mkdirSync(join(laneDir, '.ai'), { recursive: true });
      writeJson(join(laneDir, '.ai', '.lane.json'), { lane: name, number, containerId: ctx.id, container: ctx.root });
    }
    written.push('.ai/.lane.json');
  }
  put('.ai/README.md', template('lane-ai-readme.md'));
  put('.ai/context/README.md', template('lane-context-readme.md'));
  put('.ai/plans/README.md', template('lane-plans-readme.md'));
  put('.laines.env', laneEnv(envArgs(ctx, lane)));

  const local = template('lane-local-instructions.md');
  const agents = ctx.config.agents;
  if (agents.includes('claude')) {
    put('CLAUDE.local.md', local);
    const rel = '.claude/settings.local.json';
    if (!tracked(rel)) {
      if (!dryRun) {
        const file = join(laneDir, rel);
        mergeDenyRules(file, denyRules());
        const data = readJson(file);
        if (data.plansDirectory === undefined) writeJson(file, { ...data, plansDirectory: '.ai/plans' });
      }
      written.push(rel);
    }
    if (!tracked('.mcp.json')) {
      if (!dryRun) mergeMcpConfig(join(laneDir, '.mcp.json'), ctx.root);
      written.push('.mcp.json');
    }
  }
  if (agents.includes('codex')) put('AGENTS.md', local);
  if (agents.includes('gemini')) put('GEMINI.md', local);
  return { written, skipped };
}
